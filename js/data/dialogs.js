// 對話與任務。
// 每個對話是一個函式：收到遊戲狀態 s，回傳一串台詞。
//   { n: '名字', t: '內容' }   有名字的台詞
//   S('內容')                  系統訊息（沒有名字，置中顯示）
//   { fx: () => {...} }        不顯示文字，只執行效果（改任務、給錢）
// 任何台詞也可以同時帶 fx，顯示時就執行。

const S = (t, fx) => ({ n: null, t, fx });
const say = (n) => (t, fx) => ({ n, t, fx });
const any = (arr) => arr[Math.floor(Math.random() * arr.length)];

// 畫面左上角顯示的任務描述
export const QUEST_TEXT = {
  wine: '把竹葉青送到江畔渡口的老周',
  wine_back: '回青石鎮向錢掌櫃覆命',
};

export const DIALOGS = {
  intro: () => [
    S('深秋，江南。你背著一柄舊劍，走進了青石鎮。'),
    S('拖動螢幕左半邊移動，按住「疾」快走。走近人或物件，按「談」互動。'),
  ],

  innkeeper: (s) => {
    const q = say('錢掌櫃');
    if (s.flags.wineDone) return [q('有空常來坐。鎮上的大小事，我知道得比說書的還多。')];
    if (s.quest === 'wine') return [q('渡口出鎮往東走就到了，沿著大路別拐彎。')];
    if (s.quest === 'wine_back') return [
      q('老周收到了？好，好！'),
      q('說好的，這碗酒你喝。還有這點跑腿錢，別嫌少。'),
      S('【獲得】銅錢 ×30', () => { s.money += 30; s.quest = null; s.flags.wineDone = true; }),
    ];
    return [
      q('這位少俠，面生得很啊。打尖還是住店？'),
      q('……都不是？那正好，幫我個忙。'),
      q('渡口的老周訂了一罈竹葉青，我這走不開。你替我送去，回來有賞。'),
      S('【獲得】竹葉青 ×1', () => { s.quest = 'wine'; }),
      S('【任務】把酒送到東邊江畔渡口的老周。'),
    ];
  },

  boatman: (s) => {
    const q = say('老周');
    if (s.quest === 'wine') return [
      q('酒？錢掌櫃那老小子終於捨得了！'),
      S('【交出】竹葉青 ×1', () => { s.quest = 'wine_back'; }),
      q('辛苦你跑一趟。這幾天江上不太平，船先不開了。'),
      S('【任務】回青石鎮向錢掌櫃覆命。'),
    ];
    if (s.quest === 'wine_back' || s.flags.wineDone) return [
      q('入夜之後江上起霧，常聽見水底有東西在翻身……'),
      q('你別笑。我划了三十年船，從沒聽過這種聲音。'),
    ];
    return [q('要過江？這幾天不開船，改日再來吧。')];
  },

  fisher: () => {
    const q = say('漁翁');
    return [q('噓——魚要上鉤了。'), q('……又跑了。年輕人，你一來，魚就跑。')];
  },

  storyteller: () => {
    const q = say('說書先生');
    return [
      q('話說那一年，大雪封江，一個少年背著一柄斷劍，走進了一座小鎮……'),
      q('欲知後事如何——'),
      q('且聽下回分解！'),
    ];
  },

  herbalist: (s) => {
    const q = say('林大夫');
    const lines = [q('近來染風寒的人多。你行走江湖，也要顧著身子。')];
    if (s.quest === 'wine') lines.push(q('竹葉青？送人的吧。自己少喝點，傷肝。'));
    return lines;
  },

  smith: () => [say('老韓')('刀要磨，劍要養。等你找到好鐵，再來找我。')],

  child: () => [say('阿福')(any([
    '大哥哥，你會飛簷走壁嗎？',
    '我長大也要當大俠！娘說要先把字練好……',
    '那棵大樹上有鳥窩，我爬不上去。',
  ]))],

  granny: () => {
    const q = say('王婆婆');
    return [q('年輕人，天涼了，多穿件衣裳。'), q('我家老頭子年輕時也是走江湖的。後來……唉，不說了。')];
  },

  guard: () => {
    const q = say('守衛');
    return [q('北邊山路封了，聽說有山賊出沒。'), q('沒有官府文書，誰也不能過。')];
  },

  // 物件
  door: () => [S('門閂著，裡面沒人應聲。')],
  well: () => [S('井水清涼，映出你風塵僕僕的臉。')],
  barricade: () => [S('木柵擋住了山路。')],
  sign_town: () => [S('【青石鎮】往東：江畔渡口')],
  sign_west: () => [S('【告示】西路山石崩落，暫停通行。')],
  sign_dock: () => [S('【江畔渡口】風大浪急，暫停擺渡。')],
  boat: () => [S('船上空無一人，只有一盞熄了的燈籠。')],
};
